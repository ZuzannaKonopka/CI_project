"""Milestone 1 - case studies on three key benchmark cases and on hand-written models.

  python scripts/m1_case_studies.py

1. Recruitment (P01): do all traces of the reference WF-net satisfy the rules of the description (actions a..i)?
2. Business trip (P02, inclusive OR) and document submission (P03, loop):
   which traces does the WF-net allow?
3. Validator: messages for a tree with deliberate format errors.
4. Soundness vs. fidelity: a plausible but simplified recruitment tree.
5. Soundness checker: a hand-written WF-net with an AND-split closed by an XOR-join.
Output: results/m1_case_studies/{case_studies.md, case_studies.json}
"""
import os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT); os.chdir(ROOT)
import json
from nl2wfnet.benchmark import load_benchmark
from nl2wfnet.tree import parse_tree, validate_tree, tree_to_string
from nl2wfnet.wfnet import tree_to_wfnet, wfnet_from_json
from nl2wfnet.analysis import check_soundness, bounded_language

OUT = "results/m1_case_studies"
MAX_LEN = 12

# short letters for the actions of the recruitment example (traces written as strings)
LETTERS = {"submit CV": "a", "screening positive": "b", "screening negative": "c",
           "technical interview positive": "d", "technical interview negative": "e",
           "manager interview positive": "f", "manager interview negative": "g",
           "make offer": "h", "reject candidate": "i"}


def recruitment_rules(trace):
    """The rules of the recruitment description, as checks on one trace
    (letters a..i). Returns the list of violated rules (empty = trace is correct)."""
    t = "".join(trace)
    pos = {x: t.index(x) for x in set(t)}
    bad = []
    if not t.startswith("a"):
        bad.append("a must come first")
    if ("b" in t) == ("c" in t):
        bad.append("exactly one of b, c (b x c)")
    if "c" in t and t != "aci":
        bad.append("c -> i, nothing else")
    if "b" in t:
        if ("d" in t) == ("e" in t):
            bad.append("exactly one of d, e (d x e)")
        if ("f" in t) == ("g" in t):
            bad.append("exactly one of f, g (f x g)")
        if any(x in t and pos[x] < pos["b"] for x in "defg"):
            bad.append("interviews only after b")
        if ("h" in t) != ("d" in t and "f" in t):
            bad.append("h if and only if d and f")
        if ("h" in t) == ("i" in t):
            bad.append("exactly one final decision (h x i)")
    if t[-1] not in "hi":
        bad.append("the case must end with h or i")
    if len(set(t)) != len(t):
        bad.append("no activity twice")
    return bad


def main():
    os.makedirs(OUT, exist_ok=True)
    bench = {b["id"]: b for b in load_benchmark()}
    res, md = {}, ["# Milestone 1 - case studies", "", "Generated by `scripts/m1_case_studies.py`.", ""]

    # 1 recruitment
    ref = tree_to_wfnet(parse_tree(bench["P01"]["reference"]["tree"]), "P01")
    traces = sorted(bounded_language(ref, MAX_LEN))
    coded = ["".join(LETTERS[x] for x in t) for t in traces]
    viol = {c: recruitment_rules(c) for c in coded}
    # interview order: both orders must be possible for every outcome combination
    combos = {}
    for c in coded:
        if "b" in c:
            iv = [x for x in c if x in "defg"]
            combos.setdefault(frozenset(iv), set()).add("".join(iv))
    both_orders = all(len(v) == 2 for v in combos.values())
    res["P01"] = {"traces": coded, "violations": {k: v for k, v in viol.items() if v},
                  "outcome_combinations": len(combos), "both_interview_orders_possible": both_orders}
    md += ["## 1. Recruitment (P01)", "",
           "Action letters: " + ", ".join(f"{v} = {k}" for k, v in LETTERS.items()) + ".", "",
           f"The reference WF-net allows **{len(coded)} traces**: " + ", ".join(f"`{c}`" for c in coded) + ".", "",
           f"- traces violating a rule of the description: **{sum(bool(v) for v in viol.values())}**",
           f"- interview outcome combinations: {len(combos)}; both interview orders possible for each: **{both_orders}**", ""]

    # 2 OR and loop
    for cid, title in [("P02", "inclusive OR - business trip"), ("P03", "loop - document submission")]:
        net = tree_to_wfnet(parse_tree(bench[cid]["reference"]["tree"]), cid)
        tr = sorted(bounded_language(net, MAX_LEN), key=lambda t: (len(t), t))
        res[cid] = {"n_traces": len(tr), "traces": [list(t) for t in tr]}
        md += [f"## 2. {cid}: {title}", "", f"`{tree_to_string(parse_tree(bench[cid]['reference']['tree']))}`", "",
               f"Traces with at most {MAX_LEN} activities: **{len(tr)}**", ""]
        if cid == "P02":
            mids = [t[2:-1] for t in tr]
            by_size = {k: sum(len(m) == k for m in mids) for k in (1, 2, 3)}
            res[cid]["bookings_per_trace"] = by_size
            md += [f"- 1 booking: {by_size[1]} traces, 2 bookings: {by_size[2]} (each pair in both orders), "
                   f"3 bookings: {by_size[3]} (all orders) -> any non-empty subset, in any order", ""]
        else:
            reps = sorted({t.count("resubmit documents") for t in tr})
            res[cid]["resubmissions"] = reps
            md += [f"- number of resubmissions in the allowed traces: {reps} (limited only by the trace bound)", ""]
            md += ["  - " + " -> ".join(t) for t in tr[:2]] + [""]

    # 3 validator
    bad = json.load(open("data/examples/invalid_tree.json"))
    errs = validate_tree(bad["tree"])
    res["validator_messages"] = errs
    md += ["## 3. Validator messages (hand-written tree with format errors)", ""] + [f"- `{e}`" for e in errs] + [""]

    # 4 soundness vs fidelity
    simp = tree_to_wfnet(parse_tree(json.load(open("data/examples/P01_simplified_tree.json"))["tree"]), "simplified")
    A, B = bounded_language(simp, MAX_LEN), bounded_language(ref, MAX_LEN)
    p, r = len(A & B) / len(A), len(A & B) / len(B)
    extra = sorted("".join(LETTERS[x] for x in t) for t in A - B)
    res["P01_simplified"] = {"sound": check_soundness(simp)["sound"], "traces": len(A), "reference_traces": len(B),
                             "trace_precision": round(p, 3), "trace_recall": round(r, 3), "extra_traces": extra}
    md += ["## 4. Soundness is not fidelity: simplified recruitment tree", "",
           f"Sound: **{res['P01_simplified']['sound']}** | traces: {len(A)} vs. {len(B)} in the reference | "
           f"trace precision **{p:.2f}**, recall **{r:.2f}**", "",
           "Traces the simplified tree allows but the description forbids: " + ", ".join(f"`{x}`" for x in extra), ""]

    # 5 unsound net
    un = check_soundness(wfnet_from_json(json.load(open("data/examples/unsound_wfnet.json"))))
    keys = ["sound", "option_to_complete", "proper_completion", "no_dead_transitions", "states"]
    res["unsound_wfnet"] = {k: un[k] for k in keys}
    md += ["## 5. Soundness checker on a hand-written unsound WF-net (AND-split, XOR-join)", "",
           "| " + " | ".join(keys) + " |", "|" + "---|" * len(keys), "| " + " | ".join(str(un[k]) for k in keys) + " |", ""]

    json.dump(res, open(f"{OUT}/case_studies.json", "w"), indent=1)
    open(f"{OUT}/case_studies.md", "w").write("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
